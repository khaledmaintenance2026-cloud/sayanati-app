/// عدّلوا هذا الرابط ليطابق سيرفركم فعليًا:
///
/// • من داخل شبكة المصنع نفسها (نفس الواي فاي): استخدموا عنوان IP الجهاز
///   الذي يُشغّل السيرفر على المنفذ 3000، مثال:
///     const String kApiBaseUrl = 'http://192.168.1.100:3000/api';
///
/// • للوصول من خارج المصنع عبر Cloudflare Tunnel: استخدموا الرابط الذي
///   تعطيكم إياه أداة cloudflared عند تشغيلها، بنفس الصيغة مع إضافة /api:
///     const String kApiBaseUrl = 'https://xxxxx.trycloudflare.com/api';
///
///   ⚠️ تنبيه مهم: روابط trycloudflare.com المجانية "روابط سريعة" (Quick
///   Tunnels) — وهي مؤقتة وتتغيّر في كل مرة تُعاد فيها تشغيل cloudflared.
///   إن استخدمتم رابطًا من هذا النوع فسيتوقف التطبيق عن الاتصال بالسيرفر
///   بعد أي إعادة تشغيل له، ويلزم تحديث هذا الثابت وإعادة بناء APK من جديد.
///   للحصول على رابط دائم لا يتغيّر، استخدموا Named Tunnel مربوطًا بدومين
///   حقيقي (راجع README.md في مشروع السيرفر لخطوات ذلك) — عندها هذا الثابت
///   لن يحتاج تعديلًا مرة أخرى أبدًا.
